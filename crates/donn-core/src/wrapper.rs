//! bin wrapper 生成：profile 名就是命令名。
//! wrapper 只委托回 donn 本体，不复制逻辑；升级 donn 就升级了所有 wrapper。

use std::path::{Path, PathBuf};

use crate::error::{Error, Result, io_ctx};
use crate::fsx;
use crate::home::validate_name;

/// 首行标记：doctor 和删除逻辑靠它识别归属，绝不删除不是 donn 生成的同名文件。
pub const OWNERSHIP_MARK: &str = "generated by donn";

/// 与 claude、donn 本体冲突的保留名。
const RESERVED_NAMES: &[&str] = &["claude", "donn"];

/// wrapper 文件路径（Windows 加 `.cmd` 后缀）。
pub fn wrapper_path(bin_dir: &Path, alias: &str) -> PathBuf {
    if cfg!(windows) {
        bin_dir.join(format!("{alias}.cmd"))
    } else {
        bin_dir.join(alias)
    }
}

/// PATH 冲突检查：保留名直接拒绝；PATH 上已有非 donn 的同名命令时拒绝并给出路径；
/// 已被其它 profile 的 donn wrapper 占用时拒绝，绝不静默覆盖；
/// 如果 wrapper 指向 `for_profile` 自己，允许覆盖（重建场景）。
pub fn check_alias_conflict(bin_dir: &Path, alias: &str, for_profile: &str) -> Result<()> {
    validate_name(alias)?;
    if RESERVED_NAMES.contains(&alias) {
        return Err(Error::AliasConflict(
            alias.to_string(),
            PathBuf::from("<reserved>"),
        ));
    }

    let ours = wrapper_path(bin_dir, alias);
    let mut candidates: Vec<PathBuf> = Vec::new();
    if ours.exists() {
        candidates.push(ours.clone());
    }
    if let Ok(found) = which::which(alias)
        && found != ours
    {
        candidates.push(found);
    }
    for path in candidates {
        // 候选文件读不了（权限或 IO）就直接报 IO 错误，不猜归属
        if !is_donn_wrapper(&path)? {
            return Err(Error::AliasConflict(alias.to_string(), path));
        }
        match wrapper_target(&path)? {
            Some(target) if target == for_profile => {}
            Some(target) => {
                return Err(Error::AliasInUse {
                    alias: alias.to_string(),
                    profile: target,
                    path,
                });
            }
            None => return Err(Error::AliasConflict(alias.to_string(), path)),
        }
    }
    Ok(())
}

/// 生成 wrapper。`donn_exe` 是创建时的 donn 绝对路径；
/// 文件不存在或已损坏时，脚本里退回 `command -v donn`。
pub fn generate(bin_dir: &Path, alias: &str, profile: &str, donn_exe: &Path) -> Result<PathBuf> {
    validate_name(alias)?;
    let path = wrapper_path(bin_dir, alias);
    if path.exists() && !is_donn_wrapper(&path)? {
        return Err(Error::NotOwnedByDonn(path));
    }

    let content = if cfg!(windows) {
        format!(
            "@echo off\r\nrem {OWNERSHIP_MARK} \u{2014} do not edit\r\n\"{}\" run {profile} -- %*\r\n",
            donn_exe.display()
        )
    } else {
        let executable = donn_exe.to_str().ok_or_else(|| {
            Error::InvalidInput(format!(
                "donn executable path is not valid UTF-8: {}",
                donn_exe.display()
            ))
        })?;
        let executable = shlex::try_quote(executable).map_err(|error| {
            Error::InvalidInput(format!(
                "donn executable path cannot be represented in a shell wrapper: {error}"
            ))
        })?;
        format!(
            r#"#!/bin/sh
# {OWNERSHIP_MARK} — do not edit
DONN={executable}
[ -x "$DONN" ] || DONN="$(command -v donn)" || {{ echo "donn not found; reinstall donn or run: donn doctor" >&2; exit 127; }}
exec "$DONN" run {profile} -- "$@"
"#
        )
    };

    fsx::write_atomic(&path, content.as_bytes())?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))
            .map_err(io_ctx(format!("failed to chmod {}", path.display())))?;
    }

    Ok(path)
}

/// 删除属于指定 profile 的 wrapper。文件不存在视为成功；即使 spec 被手改，
/// 也绝不删除其它 profile 的同名 wrapper。
pub fn remove(bin_dir: &Path, alias: &str, expected_profile: &str) -> Result<()> {
    let path = wrapper_path(bin_dir, alias);
    if !path.exists() {
        return Ok(());
    }
    if !is_donn_wrapper(&path)? {
        return Err(Error::NotOwnedByDonn(path));
    }
    match wrapper_target(&path)? {
        Some(target) if target == expected_profile => {}
        Some(profile) => {
            return Err(Error::AliasInUse {
                alias: alias.to_string(),
                profile,
                path,
            });
        }
        None => return Err(Error::AliasConflict(alias.to_string(), path)),
    }
    std::fs::remove_file(&path).map_err(io_ctx(format!("failed to remove {}", path.display())))
}

/// 判断文件是不是 donn 生成的（前两行里有标记）。
/// IO 错误（权限等）传给调用方；非 UTF-8 内容（同名二进制）视为不是 donn wrapper。
pub fn is_donn_wrapper(path: &Path) -> Result<bool> {
    let text = read_lossy(path)?;
    Ok(text
        .lines()
        .take(2)
        .any(|line| line.contains(OWNERSHIP_MARK)))
}

/// wrapper 指向的 profile 名。只认 [`generate`] 产出的完整启动行，路径里的
/// ` run ` 等文本不能被误当成 profile。
pub fn wrapper_target(path: &Path) -> Result<Option<String>> {
    Ok(read_lossy(path)?
        .lines()
        .find_map(|line| launch_line_target(line.trim_end()))
        .map(str::to_string))
}

/// 启动行 `exec "$DONN" run <profile> -- "$@"`（Windows：`"<donn 路径>" run <profile> -- %*`）
/// 里的 profile 名；其它形状的行返回 `None`。
fn launch_line_target(line: &str) -> Option<&str> {
    let head = line
        .strip_suffix(r#" -- "$@""#)
        .or_else(|| line.strip_suffix(" -- %*"))?;
    let (launcher, profile) = head.rsplit_once(" run ")?;
    let quoted_path = launcher
        .strip_prefix('"')
        .and_then(|rest| rest.strip_suffix('"'))
        .is_some_and(|inner| !inner.is_empty() && !inner.contains('"'));
    (validate_name(profile).is_ok() && (launcher == r#"exec "$DONN""# || quoted_path))
        .then_some(profile)
}

/// 按文本读取（lossy）：IO 错误传出去，二进制内容不报错，归属判断只看文本标记。
fn read_lossy(path: &Path) -> Result<String> {
    let bytes =
        std::fs::read(path).map_err(io_ctx(format!("failed to read {}", path.display())))?;
    Ok(String::from_utf8_lossy(&bytes).into_owned())
}

/// bin_dir 是否在 PATH 里（完成页和 doctor 提示用）。
pub fn bin_dir_in_path(bin_dir: &Path) -> bool {
    let Some(path_var) = std::env::var_os("PATH") else {
        return false;
    };
    let Ok(target) = std::path::absolute(bin_dir) else {
        return false;
    };
    std::env::split_paths(&path_var)
        .filter(|path| !path.as_os_str().is_empty())
        .any(|path| std::path::absolute(path).is_ok_and(|candidate| candidate == target))
}
