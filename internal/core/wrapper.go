package core

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"mvdan.cc/sh/v3/syntax"
)

const ownershipMark = "generated by donn"

var ErrWrapperOwnership = errors.New("wrapper is not owned by this profile")

func WrapperPath(bin, alias string) string {
	if runtime.GOOS == "windows" {
		alias += ".cmd"
	}
	return filepath.Join(bin, alias)
}
func WrapperTarget(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	lines := strings.Split(string(b), "\n")
	owned := false
	for _, line := range lines[:min(2, len(lines))] {
		if strings.Contains(line, ownershipMark) {
			owned = true
		}
	}
	if !owned {
		return "", nil
	}
	for _, line := range lines {
		line = strings.TrimSpace(line)
		var head string
		if strings.HasSuffix(line, ` -- "$@"`) {
			head = strings.TrimSuffix(line, ` -- "$@"`)
		} else if strings.HasSuffix(line, " -- %*") {
			head = strings.TrimSuffix(line, " -- %*")
		} else {
			continue
		}
		i := strings.LastIndex(head, " run ")
		if i < 0 {
			continue
		}
		launcher, name := head[:i], head[i+5:]
		quoted := len(launcher) > 2 && launcher[0] == '"' && launcher[len(launcher)-1] == '"' && !strings.ContainsRune(launcher[1:len(launcher)-1], '"')
		if (launcher == `exec "$DONN"` || quoted) && ValidateName(name) == nil {
			return name, nil
		}
	}
	return "", nil
}
func CheckAlias(bin, alias, profile string) error {
	if err := ValidateName(alias); err != nil {
		return err
	}
	if alias == "donn" || alias == "claude" {
		return fmt.Errorf("alias %q is reserved", alias)
	}
	ours := WrapperPath(bin, alias)
	candidates := []string{}
	if _, err := os.Lstat(ours); err == nil {
		candidates = append(candidates, ours)
	} else if !os.IsNotExist(err) {
		return err
	}
	if path, err := exec.LookPath(alias); err == nil && path != ours {
		candidates = append(candidates, path)
	}
	for _, path := range candidates {
		target, err := WrapperTarget(path)
		if err != nil {
			return err
		}
		if target != profile {
			return fmt.Errorf("alias %q conflicts with %s", alias, path)
		}
	}
	return nil
}
func GenerateWrapper(bin, alias, profile, exe string) (string, error) {
	if err := CheckAlias(bin, alias, profile); err != nil {
		return "", err
	}
	if err := ValidateName(profile); err != nil {
		return "", err
	}
	var content string
	if runtime.GOOS == "windows" {
		if strings.ContainsAny(exe, "\"\r\n%!") {
			return "", fmt.Errorf("executable path cannot be represented in a cmd wrapper")
		}
		content = fmt.Sprintf("@echo off\r\nrem %s — do not edit\r\n\"%s\" run %s -- %%*\r\n", ownershipMark, exe, profile)
	} else {
		quoted, err := syntax.Quote(exe, syntax.LangPOSIX)
		if err != nil {
			return "", err
		}
		content = fmt.Sprintf("#!/bin/sh\n# %s — do not edit\nDONN=%s\n[ -x \"$DONN\" ] || DONN=\"$(command -v donn)\" || { echo \"donn not found; reinstall donn or run: donn doctor\" >&2; exit 127; }\nexec \"$DONN\" run %s -- \"$@\"\n", ownershipMark, quoted, profile)
	}
	path := WrapperPath(bin, alias)
	if err := writeAtomic(path, []byte(content)); err != nil {
		return "", err
	}
	if runtime.GOOS != "windows" {
		if err := os.Chmod(path, 0755); err != nil {
			return "", err
		}
	}
	return path, nil
}
func RemoveWrapper(bin, alias, profile string) error {
	if err := ValidateName(alias); err != nil {
		return err
	}
	path := WrapperPath(bin, alias)
	target, err := WrapperTarget(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if target != profile {
		return fmt.Errorf("%w: %s", ErrWrapperOwnership, path)
	}
	return os.Remove(path)
}
func BinDirInPath(bin string) bool {
	want, err := filepath.Abs(bin)
	if err != nil {
		return false
	}
	for _, p := range filepath.SplitList(os.Getenv("PATH")) {
		if p == "" {
			continue
		}
		abs, err := filepath.Abs(p)
		if err == nil && abs == want {
			return true
		}
	}
	return false
}
